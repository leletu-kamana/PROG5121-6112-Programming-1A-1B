public class DataTypeActivity {
    public static void main(String[] args) {
        //Declaring Integer Variable
        int myAge = 19;
        //Output
        System.out.println("I am " + myAge + " years old");
        
        //Declaring Float Variable
        float myDecimalNum = 41.99f;
        //Output 
        System.out.println("My favourite decimal number is " + myDecimalNum);
        
        //Declaring Character Variable
        char myInitial = 'L';
        //Output
        System.out.println("My first Initial is " + myInitial);
        
        //Declaring Boolean Variable
        boolean likeJava = true;
        boolean dislikeJava = false;
        //Output
        System.out.println("Do I really like Java: " + likeJava);
        System.out.println("Will I ever dislike Java: " + dislikeJava);
        
        //Declaring String Variable 
        String myName = "Leletu ";
        String mySurname = "Kamana";
        //Output
        System.out.println("My full name is " + myName + mySurname);
    }
}
